      final deltaY = -1.0;
      final maxTop = 2.14;
      final clampY = deltaY.clamp(-maxTop, baseL - 0.5);
      curL = (baseL - clampY).clamp(0.5, 12.0);
      curW = baseW; // Strict Invariant: Breadth untouched!

      expect(curL, closeTo(2.14, 0.01));
      expect(curW, 10.25); // Breadth remains 100% unchanged

