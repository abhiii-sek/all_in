      curW = (baseW + deltaX).clamp(0.5, 12.0);
      curL = 2.14; // Strict Invariant: Length untouched!

      expect(curW, closeTo(11.75, 0.01));
      expect(curL, 2.14); // Length remains 100% unchanged
